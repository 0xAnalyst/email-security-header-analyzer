"""Command-line interface.

    python -m esha                      # start the web UI on http://127.0.0.1:8080
    python -m esha serve -b 0.0.0.0 -p 9000
    python -m esha analyze message.eml  # human-readable report
    python -m esha analyze message.eml --json
    cat headers.txt | python -m esha analyze -
    python -m esha rules [--json | --markdown]   # list detection rules
"""
from __future__ import annotations

import argparse
import json
import sys
import webbrowser

from . import __version__

SEV_COLOR = {"critical": "\033[1;97;41m", "high": "\033[1;31m", "medium": "\033[33m",
             "low": "\033[36m", "info": "\033[2m", "pass": "\033[32m"}
RESET = "\033[0m"


def _port_free(host: str, port: int) -> bool:
    import socket
    family = socket.AF_INET6 if ":" in host else socket.AF_INET
    with socket.socket(family, socket.SOCK_STREAM) as s:
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def _free_port(host: str, port: int, explicit: bool) -> int | None:
    """Return ``port`` if free; otherwise (unless the user chose it) the next free one."""
    if _port_free(host, port):
        return port
    if explicit:
        return None
    for candidate in range(port + 1, port + 50):
        if _port_free(host, candidate):
            return candidate
    return None


def _serve(args):
    from .app import app
    port = _free_port(args.bind, args.port, explicit=args.port_given)
    if port is None:
        print(f"Port {args.port} is already in use (Burp Suite and other proxies often use 8080).\n"
              f"Stop that program or choose another port, e.g.:  python -m esha -p 9090", file=sys.stderr)
        return 1
    if port != args.port:
        print(f"Port {args.port} is busy (often Burp Suite or another proxy); using {port} instead.")
    args.port = port
    url = f"http://{'127.0.0.1' if args.bind in ('0.0.0.0', '::') else args.bind}:{args.port}"
    print(f"ESHA {__version__} running at {url}  (Ctrl+C to stop)")
    if args.open:
        webbrowser.open(url)
    app.run(host=args.bind, port=args.port, debug=args.debug)


def _analyze(args):
    from .core import analyze
    if args.file == "-":
        text, from_file = sys.stdin.read(), False
    else:
        with open(args.file, "rb") as fh:
            data = fh.read()
        text = data.decode("utf-8", "replace")
        from_file = args.file.lower().endswith((".eml", ".msg", ".mbox"))
    report = analyze(text, from_file=from_file)
    fmt = "json" if args.json else args.format
    if args.output and fmt == "text":
        fmt = "json"  # -o without -f writes the JSON report
    if fmt != "text":
        from .core.exports import export
        content = export(report, fmt)[0]
        if args.output:
            with open(args.output, "w", encoding="utf-8", newline="") as fh:
                fh.write(content)
            print(f"Wrote {fmt} to {args.output} ({report['score']['label']}, {report['score']['value']}/100)", file=sys.stderr)
        else:
            sys.stdout.write(content if content.endswith("\n") else content + "\n")
        if args.json:
            return 0  # --json has always exited 0; kept for existing scripts
        return 2 if report["score"]["level"] == "high" else 0
    color = sys.stdout.isatty() and not args.no_color
    c = (lambda k: SEV_COLOR.get(k, "")) if color else (lambda k: "")
    r = RESET if color else ""
    s = report["summary"]
    print(f"\n{c('high' if report['score']['level']=='high' else report['score']['level'] if report['score']['level']!='low' else 'pass')}"
          f"■ {report['score']['label']}  ({report['score']['value']}/100){r}\n")
    print(f"  Subject : {s['subject']}")
    print(f"  From    : {s['from']['raw']}")
    print(f"  Date    : {s['date']}")
    a = report["auth"]
    print(f"  Auth    : SPF={a['spf']['result']}  DKIM={a['dkim']['result']}  DMARC={a['dmarc']['result']}"
          f"{' (computed)' if a['dmarc']['computed'] else ''}")
    if report["origin"]:
        o = report["origin"]
        g = o.get("geo") or {}
        print(f"  Origin  : {o['ip']} {g.get('country', '')} {('AS' + str(g['asn'])) if g.get('asn') else ''}")
    print("\n  Findings")
    for f in report["findings"]:
        print(f"   {c(f['severity'])}{f['severity'].upper():8}{r} {f['title']}" + (f" — {f['detail']}" if f["detail"] else ""))
    print(f"\n  Route ({len(report['hops'])} hops)")
    for h in report["hops"]:
        d = "" if h["delay"] is None else f"+{h['delay']:.0f}s"
        print(f"   {h['hop']:>2}. {h['from'] or '?'} [{h['from_ip'] or '-'}] → {h['by'] or '?'}  {h['with']}  {d}")
    print()
    return 2 if report["score"]["level"] == "high" else 0


def rules_markdown() -> str:
    from .core.rules import all_rules
    from .core.scoring import ScoringConfig
    cfg = ScoringConfig()
    out = ["# ESHA detection rules", "",
           "Generated by `python -m esha rules --markdown`. Do not edit by hand.", "",
           "Points are the default weights; see the README to change them. Severities in brackets are ones a rule",
           "can take depending on context (for example when DMARC passes).", "",
           "| ID | Rule | Severity | Points | Category | ATT&CK |", "| --- | --- | --- | --- | --- | --- |"]
    for r in all_rules():
        sev = r.severity + (f" ({', '.join(r.also)})" if r.also else "")
        attack = ", ".join(f"[{a['id']}]({a['url']})" for a in r.attack_refs()) or "–"
        out.append(f"| {r.id} | {r.title} | {sev} | {cfg.points(r, r.severity)} | {r.category} | {attack} |")
    out += ["", "## Details", ""]
    for r in all_rules():
        out += [f"### {r.id}: {r.title}", "", r.description, ""]
        if r.remediation:
            out += [f"**What to do:** {r.remediation}", ""]
    return "\n".join(out)


def _rules(args):
    from .core.rules import all_rules
    if args.json:
        json.dump([r.to_dict() for r in all_rules()], sys.stdout, indent=2)
        print()
    elif args.markdown:
        print(rules_markdown())
    else:
        for r in all_rules():
            print(f"{r.id}  {r.severity:8}  {r.category:14}  {r.title}")
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(prog="esha", description="Email Security Header Analyzer (ESHA)")
    p.add_argument("--version", action="version", version=__version__)
    sub = p.add_subparsers(dest="cmd")
    sp = sub.add_parser("serve", help="run the web UI (default)")
    for target in (sp, p):
        target.add_argument("-b", "--bind", default="127.0.0.1")
        target.add_argument("-p", "--port", type=int, default=None, help="port (default 8080, or the next free one)")
        target.add_argument("-d", "--debug", action="store_true")
        target.add_argument("--open", action="store_true", help="open the browser")
    ap = sub.add_parser("analyze", help="analyze an .eml / header file from the command line")
    ap.add_argument("file", help="path to .eml or text file, or - for stdin")
    ap.add_argument("--json", action="store_true", help="print the full JSON report (same as --format json)")
    ap.add_argument("-f", "--format", default="text", choices=["text", "json", "iocs", "csv", "stix", "misp", "html"],
                    help="output format: text (default), json, iocs, csv, stix, misp or html")
    ap.add_argument("-o", "--output", help="write to this file instead of standard output")
    ap.add_argument("--no-color", action="store_true")
    rp = sub.add_parser("rules", help="list detection rules")
    rp.add_argument("--json", action="store_true")
    rp.add_argument("--markdown", action="store_true", help="print docs/RULES.md")
    args = p.parse_args(argv)
    args.port_given = args.port is not None
    if args.port is None:
        args.port = 8080
    if args.cmd == "rules":
        return _rules(args)
    from .core.scoring import ConfigError, get_config
    try:
        get_config()
    except ConfigError as e:
        print(f"Invalid ESHA scoring configuration: {e}", file=sys.stderr)
        return 1
    if args.cmd == "analyze":
        return _analyze(args)
    return _serve(args)


if __name__ == "__main__":
    sys.exit(main() or 0)
