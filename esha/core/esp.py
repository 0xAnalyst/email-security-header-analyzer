"""Recognise email service providers (ESPs) from header evidence.

Mail sent through an ESP normally has an envelope (Return-Path), a DKIM
signature or a Message-ID in the ESP's domain. Knowing the ESP lets ESHA
explain those mismatches instead of treating them as suspicious, and
explain why an SPF or DKIM pass for the ESP's domain proves nothing about
the From domain when DMARC fails.
"""
from __future__ import annotations

from .domains import org_domain

# name -> (domains that belong to the ESP, header names only it adds, bulk/marketing service?)
ESPS: dict[str, dict] = {
    "SendGrid": {"domains": {"sendgrid.net", "sendgrid.info", "sendgrid.com"},
                 "headers": {"x-sg-eid", "x-sg-id", "x-sendgrid-eid"}, "bulk": True},
    "Mailchimp": {"domains": {"mcsv.net", "mcdlv.net", "mailchimpapp.net", "rsgsv.net", "list-manage.com",
                              "mailchimp.com"},
                  "headers": {"x-mc-user", "x-mailchimp-campaign"}, "bulk": True},
    "Mandrill (Mailchimp Transactional)": {"domains": {"mandrillapp.com"}, "headers": {"x-mandrill-user"}, "bulk": False},
    "Amazon SES": {"domains": {"amazonses.com"}, "headers": {"x-ses-outgoing", "x-ses-configuration-set"}, "bulk": False},
    "Mailgun": {"domains": {"mailgun.org", "mailgun.net", "mailgun.info"},
                "headers": {"x-mailgun-sid", "x-mailgun-tag", "x-mailgun-variables"}, "bulk": False},
    "Salesforce Marketing Cloud": {"domains": {"exacttarget.com", "exct.net", "sfmc-content.com", "s4.exct.net"},
                                   "headers": {"x-sfmc-stack", "x-sfmc-contactkey"}, "bulk": True},
    "Postmark": {"domains": {"mtasv.net", "postmarkapp.com"}, "headers": {"x-pm-message-id", "x-pm-tag"}, "bulk": False},
    "SparkPost": {"domains": {"sparkpostmail.com", "sparkpostmail1.com", "sparkpost.com"},
                  "headers": {"x-msys-api", "x-msfbl"}, "bulk": False},
    "Brevo (Sendinblue)": {"domains": {"sendinblue.com", "brevo.com", "sendibm1.com", "sendibt2.com", "sendibt3.com"},
                           "headers": {"x-sib-id", "x-mailin-eid"}, "bulk": True},
    "HubSpot": {"domains": {"hubspotemail.net", "hubspot.com", "hs-email.net"},
                "headers": {"x-hs-cid", "x-hubspot-mid"}, "bulk": True},
    # Receiving Microsoft 365 / Gmail servers add their own X- headers, so these two
    # are only recognised from sending-side evidence (DKIM, envelope, Message-ID, origin server).
    "Microsoft 365": {"domains": {"outlook.com", "onmicrosoft.com", "office365.com", "protection.outlook.com"},
                      "headers": set(), "bulk": False},
    "Google Workspace": {"domains": {"google.com", "gappssmtp.com", "googlemail.com"},
                         "headers": {"x-gm-message-state"}, "bulk": False},
}

_DOMAIN_TO_ESP = {org_domain(d): name for name, e in ESPS.items() for d in e["domains"]}


def esp_of_domain(domain: str) -> str | None:
    """The ESP that owns ``domain`` (by organisational domain), if any."""
    return _DOMAIN_TO_ESP.get(org_domain(domain or "")) if domain else None


def detect(headers: dict[str, list[str]], *, envelope: str = "", dkim_domains: list[str] = (),
           message_id_domain: str = "", relay_hosts: list[str] = ()) -> dict | None:
    """Return {"name", "bulk", "evidence": [...], "domains": [...]} for the most likely ESP.

    ``relay_hosts`` are the origin server's HELO name and reverse DNS. Later
    hops are the receiving side and say nothing about how the mail was sent.
    """
    scores: dict[str, list[str]] = {}
    envelope = (envelope or "").rsplit("@", 1)[-1]  # accept an address or a domain

    def hit(name, why):
        scores.setdefault(name, []).append(why)

    for d in dkim_domains:
        if esp_of_domain(d):
            hit(esp_of_domain(d), f"DKIM signed by {d}")
    if esp_of_domain(envelope):
        hit(esp_of_domain(envelope), f"envelope sender at {envelope}")
    if esp_of_domain(message_id_domain):
        hit(esp_of_domain(message_id_domain), f"Message-ID generated by {message_id_domain}")
    for h in dict.fromkeys(relay_hosts):
        if h and "." in h and esp_of_domain(h):
            hit(esp_of_domain(h), f"relayed by {h}")
    names = set(headers)
    for name, e in ESPS.items():
        for hdr in sorted(e["headers"] & names):
            hit(name, f"{hdr} header")
    fid = " ".join(headers.get("feedback-id", [])).lower()
    if "amazonses" in fid or ":ses" in fid:
        hit("Amazon SES", "Feedback-ID")
    if not scores:
        return None
    # Mail from Google/Microsoft relays only counts as "sent through" them when there
    # is more than one piece of evidence (their servers also relay ordinary mail).
    name, evidence = max(scores.items(), key=lambda kv: len(kv[1]))
    if name in ("Google Workspace", "Microsoft 365") and len(evidence) < 2:
        return None
    return {"name": name, "bulk": ESPS[name]["bulk"], "evidence": evidence,
            "domains": sorted(ESPS[name]["domains"])}
